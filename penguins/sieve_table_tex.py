#!/usr/bin/env python3
# Written by the authors and refactored with the assistance of Claude (Anthropic, Claude Code).
"""Emit the bodies of tab:sieve_ablation and tab:sieve_map, so no cell in either
table is typed by hand.

One filter, four tests, and only the border test varies. Every row of both tables
holds tests 1 to 3 fixed and names the border rule it uses by its threshold. Rows
are therefore comparable within a corpus by parameter alone, with no appeal to
when or how a configuration was run.

The mask mAP table runs on the "asrun" base, the configuration every mask mAP in
the paper is computed under, so its rows are comparable with the per-corpus and
fusion tables. Its "None" row reproduces the published 69.0 and 38.7 exactly. The
counting table runs on the sieve's own constants, which is the base its
precision and count figures were always reported under.

The two tables come from two harnesses and are not cell-compatible: the counting
table takes mask areas for the geometric tests, the mask mAP table takes box
areas, so kept counts differ by a few percent. They are reported as separate
tables for that reason, never as columns of one row.

Writes fragments the paper \\input's, so a re-run of sieve_composition.py plus
relsize_stratified_recompute.py plus this script is the whole update path.
"""
import json
from pathlib import Path

COMP = Path.home() / "bench_any" / "runs" / "p5_sieve_composition" / "sieve_composition.json"
MAP = Path.home() / "bench_any" / "runs" / "p5_relsize_stratified" / "relsize_stratified.json"
PAPERS = (Path.home() / "paper"
          )

CORPORA = [("Boulders", "boulders-penguin"), ("SANParks", "sanparks-algoa")]

# Display label, sieve_composition arm key, relsize_stratified arm key.
RULES = [("None", "none", "none"),
         ("Absolute, 4\\,px margin, 8\\,$\\times$\\,324\\,px", "area", "stub"),
         ("Relative, median interior box area, $k=0.5$", "relsize", "relsize_0.50"),
         ("Relative, image median box area, $k=0.6$", "fiftyone", "fiftyone")]
SHADE = "fiftyone"


def _row(cells, shade=False, bold=()):
    cells = [f"\\textbf{{{c}}}" if i in bold else c for i, c in enumerate(cells)]
    prefix = "\\rowcolor{blue!12}" if shade else ""
    return prefix + " & ".join(cells) + " \\\\"


def counting_table(data):
    lines = ["\\begin{tabular}{lccc}", "\\toprule",
             "\\textbf{Border test} & \\textbf{Precision} & \\textbf{Recall} "
             "& \\textbf{Count MAE} \\\\", "\\midrule"]
    for i, (name, key) in enumerate(CORPORA):
        c = data[key]
        if i:
            lines.append("\\midrule")
        lines.append(f"\\multicolumn{{4}}{{l}}{{\\textit{{{name}}}}} \\\\")
        r = c["raw"]
        lines.append(_row(["SAM~3, no sieve", f"{r['precision']:.3f}",
                           f"{r['recall']:.3f}", f"{r['count_mae']:.2f}"]))
        for label, arm, _ in RULES:
            b = c["bake_off"][arm]
            shade = arm == SHADE
            lines.append(_row([label, f"{b['precision']:.3f}", f"{b['recall']:.3f}",
                               f"{b['count_mae']:.2f}"],
                              shade=shade, bold=(1, 3) if shade else ()))
    return lines + ["\\bottomrule", "\\end{tabular}"]


def map_table(data):
    lines = ["\\begin{tabular}{lcccc}", "\\toprule",
             "\\textbf{Border test} & \\textbf{Easy} & \\textbf{Medium} "
             "& \\textbf{Hard} & \\textbf{Aggregate} \\\\", "\\midrule"]
    for i, (name, key) in enumerate(CORPORA):
        arms = data[key]["bases"]["asrun"]["arms"]
        if i:
            lines.append("\\midrule")
        lines.append(f"\\multicolumn{{5}}{{l}}{{\\textit{{{name}}}}} \\\\")
        for label, _, arm in RULES:
            a = arms[arm]
            shade = arm == SHADE
            lines.append(_row([label, f"{a['easy']:.1f}", f"{a['medium']:.1f}",
                               f"{a['hard']:.1f}", f"{a['agg']:.1f}"],
                              shade=shade, bold=(3, 4) if shade else ()))
    return lines + ["\\bottomrule", "\\end{tabular}"]


def main():
    head = "% Generated by penguins/sieve_table_tex.py. Do not edit.\n"
    for fname, lines in (("tab_sieve_ablation_body.tex",
                          counting_table(json.load(open(COMP))["corpora"])),
                         ("tab_sieve_map_body.tex",
                          map_table(json.load(open(MAP))["corpora"]))):
        (PAPERS / fname).write_text(head + "\n".join(lines) + "\n")
        print(f"{len(lines)} lines -> {PAPERS / fname}", flush=True)


if __name__ == "__main__":
    main()
